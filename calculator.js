function add(a, b) {
  return a + b;
}

function subtract(a, b) {
  return a - b;
}

function multiply(a, b) {
  return a * b;
}

function divide(a, b) {
  return a / b;
}

function modulo(a, b) {
  return a % b;
}

function power(a, b) {
  return a ** b;
}

function squareRoot(a) {
  return Math.sqrt(a);
}

module.exports = { add, subtract, multiply, divide, modulo, power, squareRoot };
